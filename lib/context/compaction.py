from typing import List, Dict, Any, Optional
import re

COMPACTION_PROMPT = """You are a conversation summarizer. Your task is to compress chat history into a concise summary while preserving key information.

Instructions:
1. Extract key entities (stock tickers, company names, strategies, decisions)
2. Summarize the main topics discussed
3. Preserve important numbers, dates, and conclusions
4. Keep the summary under {max_tokens} tokens
5. Use bullet points for clarity

Format:
- Key entities: [list]
- Summary: [2-3 sentences]
- Decisions made: [list]
- Outstanding questions: [list]"""

ENTITY_EXTRACTION_PROMPT = """Extract all financial entities from this conversation.

For each entity, identify:
- Type: ticker, company, strategy, concept, decision, or other
- Value: the actual entity name/symbol
- Context: what was said about it

Return as JSON array:
[{{"type": "ticker", "value": "AAPL", "context": "User discussed AAPL fundamentals"}},
{{"type": "strategy", "value": "momentum_v1", "context": "Created momentum strategy"}}]"""

class Autocompaction:
    def __init__(self, llm_wrapper=None, max_tokens: int = 2000):
        self.llm_wrapper = llm_wrapper
        self.max_tokens = max_tokens
    
    async def summarize_turns(
        self,
        messages: List[Dict[str, Any]],
        turn_start: int,
        turn_end: int
    ) -> Dict[str, Any]:
        relevant_msgs = messages[turn_start:turn_end]
        
        conversation_text = "\n".join([
            f"{msg.get('role', 'user')}: {msg.get('content', '')[:500]}"
            for msg in relevant_msgs
        ])
        
        prompt = COMPACTION_PROMPT.format(max_tokens=self.max_tokens)
        prompt += f"\n\nConversation to summarize:\n{conversation_text}"
        
        summary_text = await self._call_llm(prompt)
        
        entities = await self.extract_entities(conversation_text)
        
        return {
            "turn_start": turn_start,
            "turn_end": turn_end,
            "summary_text": summary_text,
            "key_entities": entities,
            "token_count": len(summary_text.split())
        }
    
    async def extract_entities(self, text: str) -> List[Dict[str, Any]]:
        tickers = re.findall(r'\b[A-Z]{2,5}\b', text)
        tickers = [t for t in set(tickers) if t not in ["API", "LLM", "USD", "EUR", "GDP", "SEC", "ETF"]]
        
        strategy_patterns = [
            r'strategy[:\s]+["\']?(\w+)',
            r'called[:\s]+["\']?(\w+strategy)',
            r'created[:\s]+(\w+)\s+strategy',
        ]
        
        entities = []
        
        for ticker in tickers[:10]:
            entities.append({
                "type": "ticker",
                "value": ticker,
                "context": "Mentioned in conversation"
            })
        
        for pattern in strategy_patterns:
            matches = re.findall(pattern, text, re.IGNORECASE)
            for match in matches:
                entities.append({
                    "type": "strategy",
                    "value": match,
                    "context": "Strategy discussed"
                })
        
        return entities
    
    def should_compact(
        self,
        message_count: int,
        total_tokens: int,
        threshold: float = 0.8
    ) -> bool:
        return message_count > 10 and total_tokens > 50000
    
    def get_compaction_plan(
        self,
        message_count: int,
        total_tokens: int
    ) -> List[Dict[str, Any]]:
        if message_count <= 10:
            return []
        
        if message_count <= 20:
            return [
                {"action": "summarize", "turn_start": 0, "turn_end": message_count - 10}
            ]
        
        return [
            {"action": "summarize", "turn_start": 0, "turn_end": 10},
            {"action": "summarize", "turn_start": 10, "turn_end": message_count - 10},
        ]
    
    async def _call_llm(self, prompt: str) -> str:
        if self.llm_wrapper:
            messages = [{"role": "user", "content": prompt}]
            return await self.llm_wrapper.generate(messages)
        
        return "[Summary would be generated by LLM]"
